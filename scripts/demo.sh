#!/usr/bin/env bash
# Runnable local demo from independently authored synthetic fixtures only.
# Creates a disposable demo directory holding a synthetic schema-23 library
# (30 captures, 3 albums, one discrete JPEG focus stack) and a fresh, empty
# application state, then serves Lytronaut on 127.0.0.1. No private library,
# photograph, identifier or serial number is read or written.
set -euo pipefail
target_root=${CARGO_TARGET_DIR:-target}
case "$target_root" in /*) ;; *) target_root="$(pwd)/$target_root";; esac
test -x "$target_root/debug/lytronaut-service" || { echo 'run `just demo` (builds the service first)' >&2; exit 1; }
test -f dist/lytronaut_client_bg.wasm || { echo 'run `just demo` (builds the Rust/WASM client first)' >&2; exit 1; }
demo=${LYTRONAUT_DEMO_DIR:-$(mktemp -d "${TMPDIR:-/tmp}/lytronaut-demo.XXXXXX")}
mkdir -p "$demo"
chmod 700 "$demo"
"$target_root/debug/examples/synthetic_jpeg" "$demo/synthetic.jpg"
if [[ ${LYTRONAUT_DEMO_VIDEO:-0} == 1 ]]; then
    # Optional: a synthetic H.264 focus stack generated by headless Chrome
    # WebCodecs (needs `npm ci --ignore-scripts --prefix scripts/browser`).
    LYTRONAUT_VIDEO_FIXTURE_OUT="$demo/synthetic.video.lfp" node scripts/video-test.cjs >/dev/null
fi
python3 scripts/synthetic-library.py "$demo"
install -d -m 700 "$demo/data" # the service requires a private state directory
listen=${LYTRONAUT_LISTEN:-127.0.0.1:3000}
cat <<EOF
Lytronaut demo (synthetic data only)
  application state: $demo/data
  library folder:    $demo/Synthetic.lytrolibrary
  library ZIP:       $demo/synthetic.zip
Open http://$listen, use IMPORT LIBRARY > "Library directory" (or "ZIP library
archive") and select one of the paths above. 'Synthetic 000' carries a discrete JPEG focus stack.
Stop with Ctrl-C; delete $demo when finished.
EOF
LYTRONAUT_DATA="$demo/data" LYTRONAUT_LISTEN="$listen" LYTRONAUT_ORIGIN="http://$listen" \
    exec "$target_root/debug/lytronaut-service"
