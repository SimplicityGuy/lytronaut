//! Deterministic dependency boundary and redistribution evidence checks.
use serde_json::Value;
use std::{
    collections::BTreeSet,
    error::Error,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

type Result<T> = std::result::Result<T, Box<dyn Error>>;
fn cargo(args: &[&str]) -> Result<String> {
    let output = Command::new("cargo").args(args).output()?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into_owned().into());
    }
    Ok(String::from_utf8(output.stdout)?)
}
fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("boundaries") => boundaries(),
        Some("licenses") => licenses(args.iter().any(|a| a == "--write")),
        _ => Err("usage: cargo run -p xtask -- boundaries|licenses [--write]".into()),
    }
}
fn boundaries() -> Result<()> {
    let host_info = Command::new("rustc").arg("-vV").output()?;
    let info = String::from_utf8(host_info.stdout)?;
    let host = info
        .lines()
        .find_map(|line| line.strip_prefix("host: "))
        .ok_or("missing host target")?;
    for (package, target, denied) in [
        (
            "lytronaut-format",
            host,
            &[
                "ffmpeg",
                "ffmpeg-sys-next",
                "opencv",
                "openh264",
                "cxx",
                "bindgen",
            ][..],
        ),
        (
            "lytronaut-format",
            "wasm32-unknown-unknown",
            &[
                "ffmpeg",
                "ffmpeg-sys-next",
                "opencv",
                "openh264",
                "cxx",
                "bindgen",
                "sqlx",
                "libsqlite3-sys",
            ][..],
        ),
        (
            "lytronaut-service",
            host,
            &["leptos", "wasm-bindgen", "web-sys", "js-sys", "wgpu"][..],
        ),
        (
            "lytronaut-client",
            "wasm32-unknown-unknown",
            &[
                "sqlx",
                "libsqlite3-sys",
                "tokio",
                "axum",
                "ffmpeg-sys-next",
                "opencv",
            ][..],
        ),
    ] {
        let graph = cargo(&[
            "tree",
            "--locked",
            "-p",
            package,
            "--target",
            target,
            "--edges",
            "normal,build",
            "--prefix",
            "none",
            "--format",
            "{p}",
        ])?;
        for line in graph.lines() {
            let name = line.split_whitespace().next().unwrap_or("");
            if denied
                .iter()
                .any(|prefix| name == *prefix || name.starts_with(&format!("{prefix}-")))
            {
                return Err(format!("{package}/{target} forbidden dependency: {name}").into());
            }
        }
        println!("{package}/{target}: dependency boundary verified");
    }
    Ok(())
}
fn legal_files(root: &Path, depth: u8, files: &mut BTreeSet<PathBuf>) -> Result<()> {
    for entry in fs::read_dir(root)? {
        let entry = entry?;
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_uppercase();
        if path.is_file()
            && [
                "LICENSE",
                "LICENCE",
                "COPYING",
                "COPYRIGHT",
                "NOTICE",
                "UNLICENSE",
                "AUTHORS",
            ]
            .iter()
            .any(|n| name.starts_with(n))
        {
            files.insert(path);
        } else if path.is_dir()
            && depth < 3
            && ["LICENSES", "LICENCES", "LEGAL", "LICENSE"].contains(&name.as_str())
        {
            legal_files(&path, depth + 1, files)?;
        }
    }
    Ok(())
}
fn licenses(write: bool) -> Result<()> {
    let metadata: Value =
        serde_json::from_str(&cargo(&["metadata", "--locked", "--format-version", "1"])?)?;
    let mut packages: Vec<&Value> = metadata["packages"]
        .as_array()
        .ok_or("no metadata packages")?
        .iter()
        .filter(|p| !p["source"].is_null())
        .collect();
    packages.sort_by_key(|p| {
        format!(
            "{} {}",
            p["name"].as_str().unwrap(),
            p["version"].as_str().unwrap()
        )
    });
    let mut inventory = String::from(
        "# Resolved dependency licenses\n\nGenerated by `just licenses-update` from the entire locked workspace graph, including\nWASM, build and test dependencies. Exact versions and upstream notices are checked\nby `just licenses`. SPDX alternatives permit the permissive branch shown upstream.\nTool executables installed by mise are not shipped with Lytronaut.\n\n| Package | Version | SPDX license |\n|---|---|---|\n",
    );
    let mut notices = String::from(
        "# Third-party notices\n\nOriginal Lytronaut code is MIT. The following upstream license/notice texts and explicit declarations\naccompany the complete resolved Cargo workspace graph. Research references\nin README are acknowledged but no code from those projects is bundled.\nSQLite's bundled C database engine is public domain; it is a database dependency,\nnot an image/video processing runtime.\n\n",
    );
    let allowed = [
        "MIT",
        "Apache-2.0",
        "BSD-2-Clause",
        "BSD-3-Clause",
        "ISC",
        "Zlib",
        "Unicode-3.0",
        "CC0-1.0",
        "Unlicense",
        "0BSD",
        "BSL-1.0",
    ];
    for p in &packages {
        let name = p["name"].as_str().ok_or("missing package name")?;
        let version = p["version"].as_str().ok_or("missing version")?;
        let license = p["license"]
            .as_str()
            .ok_or_else(|| format!("unlicensed package {name}"))?;
        // Audited expressions select MIT when an alternative is copyleft or has
        // an exception. Preserve AND obligations; never treat an arbitrary OR
        // substring as proof that the entire expression is acceptable.
        let selected = match license {
            "MIT OR Apache-2.0 OR LGPL-2.1-or-later"
            | "Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT" => "MIT",
            "(MIT OR Apache-2.0) AND Unicode-3.0" => "MIT AND Unicode-3.0",
            "MIT AND BSD-3-Clause" => "MIT AND BSD-3-Clause",
            "BSD-3-Clause OR Apache-2.0" => "BSD-3-Clause",
            "MIT OR Apache-2.0"
            | "Apache-2.0 OR MIT"
            | "Apache-2.0/MIT"
            | "MIT/Apache-2.0"
            | "Unlicense OR MIT"
            | "Unlicense/MIT"
            | "Zlib OR Apache-2.0 OR MIT"
            | "MIT OR Apache-2.0 OR Zlib" => "MIT",
            value if allowed.contains(&value) => value,
            _ => return Err(format!("unaudited license {license} for {name}").into()),
        };
        inventory.push_str(&format!("| {name} | {version} | {license} |\n"));
        notices.push_str(&format!(
            "## {name} {version}\n\nSPDX: {license}\nSelected license: {selected}\n\n"
        ));
        let root = Path::new(p["manifest_path"].as_str().ok_or("missing manifest")?)
            .parent()
            .ok_or("missing root")?;
        let mut text_root = root.to_path_buf();
        let mut files = BTreeSet::new();
        legal_files(root, 0, &mut files)?;
        if let Some(file) = p["license_file"].as_str() {
            files.insert(root.join(file));
        }
        if files.is_empty() {
            text_root = PathBuf::from(format!("notices/licenses/{name}-{version}"));
            if text_root.is_dir() {
                legal_files(&text_root, 0, &mut files)?;
                // Stored upstream paths may have a directory prefix.
                for entry in fs::read_dir(&text_root)? {
                    let path = entry?.path();
                    if path.is_file() {
                        files.insert(path);
                    }
                }
            }
            notices.push_str("Separate license text omitted from package archive; retained license evidence, standard terms where needed, and revision provenance are stored in notices/licenses/SOURCES.txt.\n\n");
        }
        if files.is_empty() {
            return Err(format!("missing upstream license text for {name} {version}").into());
        }
        for file in files {
            let relative = file.strip_prefix(&text_root)?;
            notices.push_str(&format!(
                "### {}\n\n```text\n{}\n```\n\n",
                relative.display(),
                fs::read_to_string(&file)?.trim_end()
            ));
        }
    }
    for (path, content) in [
        ("DEPENDENCY_LICENSES.md", inventory),
        ("THIRD_PARTY_NOTICES.md", notices),
    ] {
        if write {
            fs::write(path, content)?;
        } else if fs::read_to_string(path)? != content {
            return Err(
                format!("{path} is stale; audit changes then run just licenses-update").into(),
            );
        }
    }
    println!(
        "{} resolved packages: licenses and notices verified",
        packages.len()
    );
    Ok(())
}
